// Prefer the seller's own clean product name (matched by SKU) over whatever the platform's
// listing title happens to be. sku may be a comma-joined list (an ASIN can carry multiple SKUs,
// e.g. FBA + FBM) — each candidate is tried in order. Falls back to the raw title/name when no
// SKU is available or none of them are in the sheet yet.
export function resolveProductName(rawName?: string | null, sku?: string | null): string {
  if (sku) {
    for (const candidate of sku.split(",").map((s) => s.trim()).filter(Boolean)) {
      if (SKU_NAME_MAP[candidate]) return SKU_NAME_MAP[candidate];
    }
  }
  return rawName || "";
}

