// Some ASINs never carry a usable title (catalog returns no name at all, so there's nothing to
// fuzzy-match on) — categorized directly by ASIN instead.
export const ASIN_CATEGORY_OVERRIDES: Record<string, string> = {
  B0GQLCT598: "Discontinued", // Insemination Kit 15cm pack of 5 — discontinued, excluded from Products page + exports
};

const STOPWORDS = new Set(["pack", "of", "with", "without", "and", "the", "for", "a", "an", "in", "kit", "new", "model", "type", "size"]);

const tokenize = (s: string) =>
  s.toLowerCase().replace(/[^a-z0-9\s]/g, " ").split(/\s+/)
    .filter((t) => t.length > 1 && !STOPWORDS.has(t))
    // naive singularization so "puzzles" matches "puzzle" etc.
    .map((t) => (t.length > 3 && t.endsWith("s") && !t.endsWith("ss") ? t.slice(0, -1) : t));

// Precompute token sets once — Master SKU sheet entries first, then supplemental entries for
// listings the sheet doesn't cover yet.
const ENTRY_TOKENS: { tokens: string[]; category: string }[] = [...CATEGORY_ENTRIES, ...SUPPLEMENTAL_ENTRIES].map(([name, category]) => ({
  tokens: tokenize(name),
  category,
}));

// Fuzzy-match an Amazon/Flipkart listing title to a category.
// Score = fraction of the internal name's tokens found in the title,
// weighted by token count so longer (more specific) names win ties.
// Resolution order: exact SKU match (works across every platform since SKU IDs are shared) →
// ASIN override (for listings with no usable title at all) → fuzzy title match → "Other".
export function categorizeTitle(title?: string | null, asin?: string | null, sku?: string | null): string {
  if (sku && SKU_CATEGORY_MAP[sku]) return SKU_CATEGORY_MAP[sku];
  if (asin && ASIN_CATEGORY_OVERRIDES[asin]) return ASIN_CATEGORY_OVERRIDES[asin];
  if (!title) return "Other";
  const titleTokens = new Set(tokenize(title));
  let bestScore = 0;
  let bestLen = 0;
  let bestCat = "Other";
  for (const e of ENTRY_TOKENS) {
    if (e.tokens.length === 0) continue;
    let hit = 0;
    for (const t of e.tokens) if (titleTokens.has(t)) hit++;
    const score = hit / e.tokens.length;
    if (score > bestScore || (score === bestScore && e.tokens.length > bestLen)) {
      bestScore = score;
      bestLen = e.tokens.length;
      bestCat = e.category;
    }
  }
  return bestScore >= 0.5 ? bestCat : "Other";
}

