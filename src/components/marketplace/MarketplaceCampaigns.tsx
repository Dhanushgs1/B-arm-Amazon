"use client";

import { useState, useMemo } from "react";
import { motion } from "framer-motion";
import { 
  MARKETPLACE_META, 
  generateMarketplaceCampaigns, 
  type MarketplaceId, 
  type MarketplaceCampaign 
} from "@/lib/marketplace";
import { PageHero } from "@/components/PageHero";
import { KPICard } from "@/components/KPICard";
import { DataTable } from "@/components/DataTable";
import { cn } from "@/lib/utils";

const cur = (val: number) => `₹${new Intl.NumberFormat("en-IN", { maximumFractionDigits: 0 }).format(Math.round(val || 0))}`;
const num = (val: number) => new Intl.NumberFormat("en-IN").format(Math.round(val || 0));

interface MarketplaceCampaignsProps {
  marketplace: Exclude<MarketplaceId, "amazon">;
}

export function MarketplaceCampaigns({ marketplace }: MarketplaceCampaignsProps) {
  const meta = MARKETPLACE_META[marketplace];
  const [campaigns, setCampaigns] = useState<MarketplaceCampaign[]>(() => generateMarketplaceCampaigns(marketplace));
  const [statusFilter, setStatusFilter] = useState<string>("all");

  const totalSpend = useMemo(() => campaigns.reduce((acc, c) => acc + c.spend, 0), [campaigns]);
  const totalSales = useMemo(() => campaigns.reduce((acc, c) => acc + c.sales, 0), [campaigns]);
  const totalOrders = useMemo(() => campaigns.reduce((acc, c) => acc + c.orders, 0), [campaigns]);
  const overallRoas = totalSpend ? totalSales / totalSpend : 0;

  const toggleCampaignStatus = (id: string) => {
    setCampaigns((prev) =>
      prev.map((c) => (c.id === id ? { ...c, status: c.status === "ENABLED" ? "PAUSED" : "ENABLED" } : c))
    );
  };

  const filteredCampaigns = useMemo(() => {
    if (statusFilter === "enabled") return campaigns.filter((c) => c.status === "ENABLED");
    if (statusFilter === "paused") return campaigns.filter((c) => c.status === "PAUSED");
    return campaigns;
  }, [campaigns, statusFilter]);

  const columns = [
    {
      key: "name",
      label: "Campaign Name",
      sortable: true,
      render: (val: string, row: MarketplaceCampaign) => (
        <div>
          <span className="font-extrabold text-slate-900 dark:text-white text-xs block">{val}</span>
          <span className="text-[10px] text-slate-500 dark:text-slate-400 font-mono">{row.id} • {row.type}</span>
        </div>
      ),
    },
    {
      key: "status",
      label: "Status",
      sortable: true,
      render: (val: string, row: MarketplaceCampaign) => (
        <button
          onClick={() => toggleCampaignStatus(row.id)}
          className={cn(
            "px-2.5 py-0.5 rounded-full text-[10px] font-bold uppercase border cursor-pointer transition-all",
            val === "ENABLED"
              ? "bg-emerald-500/10 text-emerald-400 border-emerald-500/20 hover:bg-emerald-500/20"
              : "bg-amber-500/10 text-amber-400 border-amber-500/20 hover:bg-amber-500/20"
          )}
        >
          {val}
        </button>
      ),
    },
    {
      key: "budget",
      label: "Daily Budget",
      sortable: true,
      render: (val: number) => cur(val),
    },
    {
      key: "spend",
      label: "Ad Spend",
      sortable: true,
      render: (val: number) => cur(val),
    },
    {
      key: "sales",
      label: "Ad Sales",
      sortable: true,
      render: (val: number) => <span className="font-extrabold text-emerald-400">{cur(val)}</span>,
    },
    {
      key: "roas",
      label: "ROAS",
      sortable: true,
      render: (val: number) => (
        <span className={cn("font-bold px-2 py-0.5 rounded text-xs", val >= 3.5 ? "text-emerald-400 bg-emerald-500/10" : "text-amber-400 bg-amber-500/10")}>
          {val.toFixed(2)}x
        </span>
      ),
    },
    {
      key: "acos",
      label: "ACOS",
      sortable: true,
      render: (val: number) => `${val.toFixed(1)}%`,
    },
    {
      key: "orders",
      label: "Orders",
      sortable: true,
      render: (val: number) => num(val),
    },
  ];

  return (
    <motion.div initial={{ opacity: 0 }} animate={{ opacity: 1 }} transition={{ duration: 0.4 }} className="space-y-6 pb-12">
      <PageHero
        title={`${meta.label} Advertising Campaigns`}
        subtitle={`Manage and analyze all ${meta.label} sponsored ads, PLA/PCA campaigns, and target performance.`}
      />

      <motion.div initial={{ opacity: 0, y: 20 }} animate={{ opacity: 1, y: 0 }} transition={{ delay: 0.1, duration: 0.5 }} className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-4">
        <KPICard title="Total Ad Spend" value={cur(totalSpend)} subtitle="across active campaigns" />
        <KPICard title="Total Ad Sales" value={cur(totalSales)} subtitle="generated by ads" />
        <KPICard title="Overall Ad ROAS" value={`${overallRoas.toFixed(2)}x`} subtitle="return on ad spend" />
        <KPICard title="Total Orders" value={num(totalOrders)} subtitle="from ad traffic" />
      </motion.div>

      <motion.div initial={{ opacity: 0, y: 20 }} animate={{ opacity: 1, y: 0 }} transition={{ delay: 0.2, duration: 0.5 }} className="flex items-center gap-2 bg-popover/60 backdrop-blur-md p-3.5 rounded-xl border border-border">
        <span className="text-xs font-extrabold text-slate-500 dark:text-slate-400 uppercase tracking-wider px-1">Status:</span>
        {["all", "enabled", "paused"].map((st) => (
          <button
            key={st}
            onClick={() => setStatusFilter(st)}
            className={cn(
              "px-3 py-1.5 rounded-lg text-xs font-bold capitalize transition-all cursor-pointer",
              statusFilter === st ? "bg-indigo-600 text-white" : "bg-slate-100 dark:bg-slate-900 text-slate-500 dark:text-slate-400 hover:text-slate-900 dark:hover:text-white"
            )}
          >
            {st}
          </button>
        ))}
      </motion.div>

      <motion.div initial={{ opacity: 0, y: 20 }} animate={{ opacity: 1, y: 0 }} transition={{ delay: 0.3, duration: 0.5 }} className="bg-popover/80 border border-border rounded-xl p-4">
        <DataTable data={filteredCampaigns} columns={columns as any} defaultSort="spend" />
      </motion.div>
    </motion.div>
  );
}
