"use client";

import { useState, useMemo } from "react";
import { useQuery } from "@tanstack/react-query";
import { Loader2 } from "lucide-react";
import { useDashboard } from "@/lib/DashboardContext";
import { KPICard } from "@/components/KPICard";
import { DataTable } from "@/components/DataTable";
import { fetchFlipkartCampaigns } from "@/lib/flipkartData";
import { cn } from "@/lib/utils";

const cur = (val: number) => `₹${new Intl.NumberFormat("en-IN", { maximumFractionDigits: 0 }).format(Math.round(val || 0))}`;
const num = (val: number) => new Intl.NumberFormat("en-IN").format(Math.round(val || 0));

export function FlipkartCampaigns() {
  const { loggedInUser, startDate, endDate } = useDashboard();
  const [statusFilter, setStatusFilter] = useState<"all" | "active" | "idle">("all");

  const { data, isLoading } = useQuery({
    queryKey: ["flipkart-campaigns", loggedInUser, startDate, endDate],
    queryFn: () => fetchFlipkartCampaigns(loggedInUser, startDate, endDate),
    enabled: !!startDate && !!endDate,
  });

  const filtered = useMemo(() => {
    if (!data) return [];
    if (statusFilter === "active") return data.rows.filter((c) => c.status === "ACTIVE");
    if (statusFilter === "idle") return data.rows.filter((c) => c.status === "IDLE");
    return data.rows;
  }, [data, statusFilter]);

  if (isLoading || !data) {
    return (
      <div className="flex h-[60vh] items-center justify-center flex-col gap-4 text-muted-foreground">
        <Loader2 className="w-8 h-8 animate-spin text-primary" />
        <p className="font-semibold text-sm">Loading Flipkart campaigns...</p>
      </div>
    );
  }

  return (
    <div className="space-y-6 pb-12">
      <div className="space-y-1 border-b border-slate-200/50 dark:border-slate-800/50 pb-4">
        <h1 className="text-3xl font-black tracking-tight text-slate-900 dark:text-white">Flipkart Advertising Campaigns</h1>
        <p className="text-slate-500 dark:text-slate-400 text-xs">{data.rows.length} campaigns · {startDate} – {endDate}</p>
      </div>

      <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-4">
        <KPICard title="Total Ad Spend" value={cur(data.totalSpend)} subtitle="Across campaigns" delay={0.02} accent="pink" />
        <KPICard title="Total Ad Sales" value={cur(data.totalSales)} subtitle="Generated by ads" delay={0.04} accent="green" />
        <KPICard title="Overall ROAS" value={`${data.overallRoas.toFixed(2)}x`} subtitle="Return on ad spend" delay={0.06} accent="purple" />
        <KPICard title="Ad Orders" value={num(data.totalOrders)} subtitle="From ad traffic" delay={0.08} accent="blue" />
      </div>

      <div className="flex items-center gap-2 bg-popover/60 backdrop-blur-md p-3.5 rounded-xl border border-border">
        <span className="text-xs font-extrabold text-slate-500 dark:text-slate-400 uppercase tracking-wider px-1">Status:</span>
        {(["all", "active", "idle"] as const).map((st) => (
          <button
            key={st}
            onClick={() => setStatusFilter(st)}
            className={cn(
              "px-3 py-1.5 rounded-lg text-xs font-bold capitalize transition-all cursor-pointer",
              statusFilter === st ? "bg-indigo-600 text-white" : "bg-slate-100 dark:bg-slate-900 text-slate-500 dark:text-slate-400 hover:text-slate-900 dark:hover:text-white"
            )}
          >
            {st}
          </button>
        ))}
      </div>

      <DataTable
        data={filtered}
        exportName="flipkart_campaigns"
        defaultSort="spend"
        columns={[
          {
            key: "name",
            label: "Campaign",
            sortable: true,
            render: (v, row: any) => (
              <div>
                <span className="font-extrabold text-slate-900 dark:text-white text-xs block max-w-[280px] truncate">{v}</span>
                <span className="text-[10px] text-slate-500 dark:text-slate-400 font-mono">{row.type}</span>
              </div>
            ),
          },
          {
            key: "status",
            label: "Status",
            sortable: true,
            render: (v) => (
              <span className={cn("px-2.5 py-0.5 rounded-full text-[10px] font-bold uppercase border", v === "ACTIVE" ? "bg-emerald-500/10 text-emerald-500 border-emerald-500/20" : "bg-slate-500/10 text-slate-400 border-slate-500/20")}>{v}</span>
            ),
          },
          { key: "spend", label: "Ad Spend", sortable: true, summable: true, render: (v) => cur(v) },
          { key: "sales", label: "Ad Sales", sortable: true, summable: true, render: (v) => <span className="font-extrabold text-emerald-500">{cur(v)}</span> },
          {
            key: "roas",
            label: "ROAS",
            sortable: true,
            render: (v) => <span className={cn("font-bold px-2 py-0.5 rounded text-xs", v >= 3.5 ? "text-emerald-500 bg-emerald-500/10" : v > 0 ? "text-amber-500 bg-amber-500/10" : "text-slate-400 bg-slate-500/10")}>{v.toFixed(2)}x</span>,
          },
          { key: "acos", label: "ACOS", sortable: true, render: (v) => `${v.toFixed(1)}%` },
          { key: "orders", label: "Orders", sortable: true, summable: true, render: (v) => num(v) },
          { key: "clicks", label: "Clicks", sortable: true, summable: true, render: (v) => num(v) },
        ]}
      />
    </div>
  );
}
