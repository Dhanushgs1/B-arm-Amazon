-- scripts/price_listing_tables.sql
-- Current price/stock/status snapshots for Amazon and Flipkart — each
-- upload fully replaces the previous one (a current-moment snapshot, no
-- date column), same FULL_REPLACE_TYPES convention as every other
-- snapshot-style table in this app. Both tables already existed live
-- before this script was written (created ad hoc, not tracked) — this is
-- `create table if not exists`, safe to run without affecting existing data.

-- Amazon "All Listings report" (Reports -> Fulfillment -> ... or
-- Inventory -> Manage All Inventory -> Preferences -> Export). Mapped by
-- mapPriceListingRow in src/lib/amazonReportUpload.ts.
create table if not exists public.barm_amazon_price_listing (
  id bigint generated by default as identity primary key,
  seller_sku text not null,
  item_name text,
  price numeric,
  business_price numeric,
  quantity integer,
  fulfillment_channel text,
  asin1 text,
  item_condition text,
  -- "Active"/"Inactive" on Amazon's own export — blank on older exports
  -- that don't carry the column at all; callers must treat blank as
  -- "unknown", never as "inactive".
  status text,
  -- Every original column from the upload, for anything not promoted to
  -- its own column above.
  raw jsonb,
  created_at timestamptz not null default now()
);
create index if not exists barm_amazon_price_listing_seller_sku_idx on public.barm_amazon_price_listing (seller_sku);

-- Flipkart "Manage Listings" export (Listings -> Manage Listings ->
-- Export). Mapped by parseListingsReport in src/lib/flipkartReportUpload.ts
-- — that parser detects and drops the template's human-readable
-- description row ("Title of your product as on Flipkart.com", ...) before
-- these columns are read.
create table if not exists public.barm_flipkart_listings (
  id bigint generated by default as identity primary key,
  listing_id text,
  seller_sku_id text not null,
  product_title text,
  selling_price numeric,
  mrp numeric,
  stock_count numeric,
  listing_status text,
  updated_at timestamptz not null default now()
);
create index if not exists barm_flipkart_listings_seller_sku_id_idx on public.barm_flipkart_listings (seller_sku_id);

-- Same RLS-disabled + anon-full-grant pattern every other table in this app
-- uses — the app has no auth session and talks to Supabase entirely with
-- the anon key.
alter table public.barm_amazon_price_listing disable row level security;
grant select, insert, update, delete on public.barm_amazon_price_listing to anon;
alter table public.barm_flipkart_listings disable row level security;
grant select, insert, update, delete on public.barm_flipkart_listings to anon;
