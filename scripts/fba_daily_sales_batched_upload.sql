-- scripts/fba_daily_sales_batched_upload.sql
-- Batched (staging + atomic commit) upload path for barm_fba_daily_sales.
-- Run once in the Supabase SQL Editor AFTER scripts/fba_forecast_tables.sql.
-- There is no migration runner in this repo, so this file must be run by hand.
--
-- Why: replace_barm_fba_daily_sales(rows) takes the WHOLE file in one
-- request and deletes-then-inserts in one call. Calling it once per batch
-- would make every batch wipe the previous one, and one huge request can die
-- in transit ("TypeError: Failed to fetch"). Instead the client now:
--   1. picks an upload session id (uuid),
--   2. stages rows 1,000 at a time into barm_fba_daily_sales_staging
--      (stage_barm_fba_daily_sales_batch) — production is untouched,
--   3. calls commit_barm_fba_daily_sales_session, which verifies the staged
--      row count equals the expected count and, in ONE transaction, replaces
--      barm_fba_daily_sales with the staged rows and clears the session.
-- If any batch fails, the client calls discard_barm_fba_daily_sales_session;
-- barm_fba_daily_sales is never touched, so it can never hold partial data.
--
-- replace_barm_fba_daily_sales is left in place (unused by the app now).

create table if not exists public.barm_fba_daily_sales_staging (
  id bigint generated by default as identity primary key,
  session_id uuid not null,
  batch_index integer not null,
  purchase_date date not null,
  fulfillment_channel text not null,
  product_name text not null,
  sku text not null,
  quantity integer not null,
  ship_state text not null,
  created_at timestamptz not null default now()
);
create index if not exists barm_fba_daily_sales_staging_session_idx
  on public.barm_fba_daily_sales_staging (session_id, batch_index);

alter table public.barm_fba_daily_sales_staging disable row level security;
grant select, insert, update, delete on public.barm_fba_daily_sales_staging to anon;
grant usage, select on all sequences in schema public to anon;

-- Stages one batch. Deletes any rows already staged for the same
-- (session, batch_index) first, so re-sending a batch can never duplicate it.
-- Returns the number of rows now staged for that batch.
create or replace function public.stage_barm_fba_daily_sales_batch(p_session_id uuid, p_batch_index integer, rows jsonb)
returns integer
language plpgsql
as $$
declare
  v_count integer;
begin
  delete from public.barm_fba_daily_sales_staging
  where session_id = p_session_id and batch_index = p_batch_index;

  insert into public.barm_fba_daily_sales_staging
    (session_id, batch_index, purchase_date, fulfillment_channel, product_name, sku, quantity, ship_state)
  select
    p_session_id,
    p_batch_index,
    (r->>'purchase_date')::date,
    r->>'fulfillment_channel',
    r->>'product_name',
    r->>'sku',
    (r->>'quantity')::integer,
    r->>'ship_state'
  from jsonb_array_elements(rows) as r;

  get diagnostics v_count = row_count;
  return v_count;
end;
$$;

-- Verifies the session's staged row count and batch count, then atomically
-- replaces barm_fba_daily_sales with the staged rows. Any mismatch raises, which
-- rolls back the whole call — production keeps its previous data.
-- Returns the final barm_fba_daily_sales row count.
create or replace function public.commit_barm_fba_daily_sales_session(p_session_id uuid, p_expected_rows integer, p_expected_batches integer)
returns integer
language plpgsql
as $$
declare
  v_staged integer;
  v_batches integer;
  v_final integer;
begin
  select count(*), count(distinct batch_index) into v_staged, v_batches
  from public.barm_fba_daily_sales_staging
  where session_id = p_session_id;

  if v_staged <> p_expected_rows or v_batches <> p_expected_batches then
    raise exception 'Staged data incomplete: % rows in % batches, expected % rows in % batches',
      v_staged, v_batches, p_expected_rows, p_expected_batches;
  end if;

  delete from public.barm_fba_daily_sales where id is not null;
  insert into public.barm_fba_daily_sales
    (purchase_date, fulfillment_channel, product_name, sku, quantity, ship_state)
  select purchase_date, fulfillment_channel, product_name, sku, quantity, ship_state
  from public.barm_fba_daily_sales_staging
  where session_id = p_session_id
  order by batch_index, id;

  select count(*) into v_final from public.barm_fba_daily_sales;
  if v_final <> p_expected_rows then
    raise exception 'Commit verification failed: barm_fba_daily_sales has % rows, expected %', v_final, p_expected_rows;
  end if;

  delete from public.barm_fba_daily_sales_staging where session_id = p_session_id;
  -- Housekeeping: drop sessions abandoned more than a day ago (closed tab, etc.).
  delete from public.barm_fba_daily_sales_staging where created_at < now() - interval '1 day';

  return v_final;
end;
$$;

-- Drops a failed/abandoned session's staged rows. Never touches production.
create or replace function public.discard_barm_fba_daily_sales_session(p_session_id uuid)
returns void
language plpgsql
as $$
begin
  delete from public.barm_fba_daily_sales_staging where session_id = p_session_id;
end;
$$;

grant execute on function public.stage_barm_fba_daily_sales_batch(uuid, integer, jsonb) to anon;
grant execute on function public.commit_barm_fba_daily_sales_session(uuid, integer, integer) to anon;
grant execute on function public.discard_barm_fba_daily_sales_session(uuid) to anon;

-- Make the new functions visible to the API immediately.
notify pgrst, 'reload schema';

