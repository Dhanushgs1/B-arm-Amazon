-- scripts/fba_forecast_report_tables.sql
-- Supports the FBA page's Generate/Download flow (zone assignment, 120-day
-- forecast, stock-needed, days-to-stockout — computed server-side in a
-- Supabase Edge Function, never in the browser). Run this once in the
-- Supabase SQL Editor, in addition to scripts/fba_forecast_tables.sql
-- (which holds the 5 raw ingestion tables this report reads from).
--
-- Same RLS-disabled + full grant to `anon` pattern every other table in
-- this app uses, and the same job-status/report-row split as the Daily Ad
-- Spend Report (scripts/report_generation_jobs_table.sql +
-- scripts/daily_ad_spend_reports_table.sql) — reused here, not
-- reinvented: report_type = 'fba_forecast' in the existing
-- report_generation_jobs table.
--
-- No manual shipment-cap table here (deliberately removed) — "To Be Sent"
-- and "Stock To Be Ordered" are computed directly from stock-needed-after-
-- inbound with no batch-size input to configure (see fbaForecastCalc.ts).

-- One row per generated report, keyed by the DASHBOARD'S SELECTED DATE
-- (report_date) — never "today". result_json mirrors
-- FbaForecastReportResult minus its non-serializable `wb` field. The actual
-- .xlsx lives in Supabase Storage (xlsx_storage_path), not inline.
create table if not exists public.fba_forecast_reports (
  id bigint generated by default as identity primary key,
  report_date date not null,
  job_id bigint references public.report_generation_jobs(id),
  result_json jsonb not null,
  xlsx_storage_path text,
  generated_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (report_date)
);

alter table public.fba_forecast_reports disable row level security;
grant select, insert, update, delete on public.fba_forecast_reports to anon;

-- Private bucket for the generated .xlsx workbooks — same pattern as
-- scripts/daily_ad_spend_reports_table.sql's "ad-spend-reports" bucket.
insert into storage.buckets (id, name, public)
values ('fba-forecast-reports', 'fba-forecast-reports', false)
on conflict (id) do nothing;

drop policy if exists "fba-forecast-reports anon read" on storage.objects;
create policy "fba-forecast-reports anon read"
  on storage.objects for select
  using (bucket_id = 'fba-forecast-reports');

drop policy if exists "fba-forecast-reports anon write" on storage.objects;
create policy "fba-forecast-reports anon write"
  on storage.objects for insert
  with check (bucket_id = 'fba-forecast-reports');

drop policy if exists "fba-forecast-reports anon update" on storage.objects;
create policy "fba-forecast-reports anon update"
  on storage.objects for update
  using (bucket_id = 'fba-forecast-reports');
