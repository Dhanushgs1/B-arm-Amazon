-- Run once in the Supabase SQL Editor, after scripts/fba_forecast_tables.sql.
-- There is no migration runner in this repo, so this file must be run by hand.

-- ── 1. barm_fba_recently_act.active_date: real per-row date ────────────────
-- active_date now holds each shipment's REAL active date, read from the FBA
-- & FBF Details month sheet's second STATUS column (e.g. "08.09.2026"),
-- instead of the upload's report date stamped on every row. This supersedes
-- the "NOT sourced from the input file" note in fba_forecast_tables.sql. A
-- few Active rows have that cell blank, so the column must allow NULL.
alter table public.barm_fba_recently_act alter column active_date drop not null;

-- ── 2. barm_fba_manual_plan: the seller's own FBA analysis sheet ──────────
-- Uploaded from the manual "FBA_forecast sheet(30 days).xlsx": its typed-in
-- SKU × zone list (skuid / zone columns, in the sheet's own row order) and
-- column X "Stock present per SKU ID for FBA - booked" (null when blank).
-- When this table has rows, the FBA Forecast Report lists every one of them
-- and computes "to be sent" / "stock to be ordered" with the manual's own
-- formulas against X. Whole-table replace on every upload.
create table if not exists public.barm_fba_manual_plan (
  id bigint generated by default as identity primary key,
  row_order integer not null,
  sku text not null,
  zone text not null,
  stock_to_send numeric,
  created_at timestamptz not null default now()
);
create index if not exists barm_fba_manual_plan_row_order_idx on public.barm_fba_manual_plan (row_order);

alter table public.barm_fba_manual_plan disable row level security;
grant select, insert, update, delete on public.barm_fba_manual_plan to anon;
grant usage, select on all sequences in schema public to anon;

create or replace function public.replace_barm_fba_manual_plan(rows jsonb)
returns integer
language plpgsql
as $$
declare
  v_count integer;
begin
  delete from public.barm_fba_manual_plan where id is not null;
  insert into public.barm_fba_manual_plan (row_order, sku, zone, stock_to_send)
  select
    (r->>'row_order')::integer,
    r->>'sku',
    r->>'zone',
    nullif(r->>'stock_to_send', '')::numeric
  from jsonb_array_elements(rows) as r;
  get diagnostics v_count = row_count;
  return v_count;
end;
$$;

grant execute on function public.replace_barm_fba_manual_plan(jsonb) to anon;

notify pgrst, 'reload schema';

