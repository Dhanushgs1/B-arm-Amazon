-- scripts/fba_forecast_tables.sql
-- Tables + RPC functions for the FBA Forecast Report upload/ingestion
-- pipeline (raw-data side only — no forecast calculation lives here). Run
-- once in the Supabase SQL Editor before the first FBA upload. There is no
-- migration runner in this repo, so this file must be pasted/run by hand.
--
-- Superseding note: an earlier draft (docs/superpowers/plans/2026-09-22-
-- fba-forecast-report.md, Task 1) used different table names
-- (barm_fba_sales_30d / barm_fba_stock / barm_fba_status_events). That
-- draft is superseded by this file — the 5 core tables below (all prefixed
-- barm_fba_) plus one un-prefixed upload_history audit table are the final
-- names. See the same plan doc's updated Tasks 1/4/5/9 for how the upload
-- pipeline itself was built against this schema.
--
-- Same RLS-disabled + full grant to `anon` pattern every other table in
-- this app uses (see scripts/fix_rls_all_tables.sql) — the app has no auth
-- session and talks to Supabase entirely with the anon key.

-- ── 1. barm_fba_daily_sales ─────────────────────────────────────────────
-- Corresponds to the SOP's `30_days_sales` sheet (source: the Amazon "All
-- Orders" report, a tab/comma-delimited text export). Whole-table replace
-- on every upload — the source report is always "last 30 days" in full, so
-- there is no natural key to upsert against.
create table if not exists public.barm_fba_daily_sales (
  id bigint generated by default as identity primary key,
  purchase_date date not null,
  fulfillment_channel text not null,
  product_name text not null,
  sku text not null,
  quantity integer not null,
  ship_state text not null,
  created_at timestamptz default now()
);
create index if not exists barm_fba_daily_sales_sku_idx on public.barm_fba_daily_sales (sku);
create index if not exists barm_fba_daily_sales_purchase_date_idx on public.barm_fba_daily_sales (purchase_date);

-- ── 2. barm_fba_stock_snapshot ──────────────────────────────────────────
-- Corresponds to the SOP's `FBA_stock` sheet (source: the FBA stock report,
-- a Custom Report Builder export). Whole-table replace on every upload; the
-- upload code itself filters to the most-recent date, non-VSNC,
-- SELLABLE-only rows before writing here.
create table if not exists public.barm_fba_stock_snapshot (
  id bigint generated by default as identity primary key,
  report_date date not null,
  fnsku text not null,
  fulfillment_center text not null,
  asin text not null,
  msku text not null,
  disposition text not null,
  ending_warehouse_balance integer not null,
  created_at timestamptz default now()
);
create index if not exists barm_fba_stock_snapshot_msku_idx on public.barm_fba_stock_snapshot (msku);
create index if not exists barm_fba_stock_snapshot_report_date_idx on public.barm_fba_stock_snapshot (report_date);

-- ── 3-5. barm_fba_booked / barm_fba_intransit / barm_fba_recently_act ──
-- Split from the "FBA & FBF Details-Updated" workbook by its first STATUS
-- column: 'Booked' -> booked, 'Picked Up' -> intransit, 'Active' ->
-- recently_act. Every other status value (e.g. "cancelled before 24hrs of
-- pickup", "Didn't send to FBA") is excluded entirely, not inserted
-- anywhere. `quantity` is the "Final shipped quantity" (column D) value for
-- all 3 categories, per the confirmed convention.
--
-- Ingestion rule: all 3 monthly sheets (current month + previous 2, e.g.
-- SEPT26/AUG26/JUL26) are parsed together in one upload, and rows are
-- de-duped WITHIN each category (never across categories — a SKU can
-- legitimately be both booked and active for different shipments) by the
-- identity key (sku, fc, quantity, booked_date, pickup_date) before
-- insert — see fbfIdentityKey's doc comment in src/lib/fbaForecastRules.ts
-- for why that key (and its accepted blank-date limitation) was chosen.
-- Each of these 3 tables then gets a FULL TABLE REPLACE on every FBA & FBF
-- Details upload (not a per-source_month delete) — all 3 relevant months
-- are always uploaded together in one workbook, and the dedup above already
-- handles cross-month re-listing correctly, so there is no stale-month data
-- left behind to worry about.
create table if not exists public.barm_fba_booked (
  id bigint generated by default as identity primary key,
  source_month text not null, -- 'YYYY-MM', for traceability only, not a delete key
  product text not null,
  sku text not null,
  quantity integer not null,
  fc text not null,
  booked_date date,
  pickup_date date,
  status_raw text not null,
  created_at timestamptz default now()
);
create index if not exists barm_fba_booked_sku_idx on public.barm_fba_booked (sku);

create table if not exists public.barm_fba_intransit (
  id bigint generated by default as identity primary key,
  source_month text not null,
  product text not null,
  sku text not null,
  quantity integer not null,
  fc text not null,
  booked_date date,
  pickup_date date,
  status_raw text not null,
  created_at timestamptz default now()
);
create index if not exists barm_fba_intransit_sku_idx on public.barm_fba_intransit (sku);

create table if not exists public.barm_fba_recently_act (
  id bigint generated by default as identity primary key,
  source_month text not null,
  product text not null,
  sku text not null,
  quantity integer not null,
  fc text not null,
  booked_date date,
  pickup_date date,
  status_raw text not null,
  -- The date THIS upload/commit ran, stamped identically on every row in
  -- the batch — NOT sourced from the input file (the workbook has no
  -- per-row "went active on" date on the Active-status rows).
  active_date date not null,
  created_at timestamptz default now()
);
create index if not exists barm_fba_recently_act_sku_idx on public.barm_fba_recently_act (sku);

-- ── 6. upload_history (NOT prefixed barm_fba_ — only the 5 tables above
-- get that prefix) ──────────────────────────────────────────────────────
-- One row per (file, target table) write. A single FBA & FBF Details
-- upload produces 3 rows here (one per target table), since it's really 3
-- independent writes bundled into one user action.
create table if not exists public.upload_history (
  upload_id bigint generated by default as identity primary key,
  file_name text not null,
  target_table text not null,
  uploaded_at timestamptz not null default now(),
  uploaded_by text not null default '',
  rows_received integer not null default 0,
  rows_accepted integer not null default 0,
  rows_rejected integer not null default 0,
  status text not null check (status in ('success', 'failed', 'partial')),
  -- e.g. {"cancelled": 12, "merchant": 3, "s_prefix_order": 1, "today_order": 5}
  -- for barm_fba_daily_sales; {"non_sellable": 8, "vsnc": 2,
  -- "older_stock_date": 40} for barm_fba_stock_snapshot;
  -- {"unrecognized_status": 14} for the booked/intransit/recently_act split.
  rejection_reasons jsonb not null default '{}'::jsonb,
  error_message text,
  created_at timestamptz not null default now()
);
create index if not exists upload_history_uploaded_at_idx on public.upload_history (uploaded_at desc);
create index if not exists upload_history_target_table_idx on public.upload_history (target_table);

-- ── RLS-disabled + full anon grant, matching every other table here ────
