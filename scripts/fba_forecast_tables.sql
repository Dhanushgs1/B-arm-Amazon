$$;

-- Replaces ALL THREE booked/intransit/recently_act tables in one function
-- body, so a failure partway through rolls back all three together — they
-- are derived from one workbook upload and must stay consistent as a set.
create or replace function public.replace_fba_fbf_details(booked jsonb, intransit jsonb, recently_act jsonb)
returns void
language plpgsql
as $$
begin
  delete from public.barm_fba_booked where id is not null;
  insert into public.barm_fba_booked
    (source_month, product, sku, quantity, fc, booked_date, pickup_date, status_raw)
  select
    r->>'source_month',
    r->>'product',
    r->>'sku',
    (r->>'quantity')::integer,
    r->>'fc',
    nullif(r->>'booked_date', '')::date,
    nullif(r->>'pickup_date', '')::date,
    r->>'status_raw'
  from jsonb_array_elements(booked) as r;

  delete from public.barm_fba_intransit where id is not null;
  insert into public.barm_fba_intransit
    (source_month, product, sku, quantity, fc, booked_date, pickup_date, status_raw)
  select
    r->>'source_month',
    r->>'product',
    r->>'sku',
    (r->>'quantity')::integer,
    r->>'fc',
    nullif(r->>'booked_date', '')::date,
    nullif(r->>'pickup_date', '')::date,
    r->>'status_raw'
  from jsonb_array_elements(intransit) as r;

  delete from public.barm_fba_recently_act where id is not null;
  insert into public.barm_fba_recently_act
    (source_month, product, sku, quantity, fc, booked_date, pickup_date, status_raw, active_date)
  select
    r->>'source_month',
    r->>'product',
    r->>'sku',
    (r->>'quantity')::integer,
    r->>'fc',
    nullif(r->>'booked_date', '')::date,
    nullif(r->>'pickup_date', '')::date,
    r->>'status_raw',
    (r->>'active_date')::date
  from jsonb_array_elements(recently_act) as r;
end;
$$;

grant execute on function public.replace_barm_fba_daily_sales(jsonb) to anon;
grant execute on function public.replace_barm_fba_stock_snapshot(jsonb) to anon;
grant execute on function public.replace_fba_fbf_details(jsonb, jsonb, jsonb) to anon;

