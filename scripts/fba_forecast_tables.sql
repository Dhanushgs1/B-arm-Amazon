-- ── Atomicity: Postgres RPC functions instead of client-side sequential
-- calls ──────────────────────────────────────────────────────────────────
-- The Supabase JS client can't run a multi-statement transaction directly,
-- so the actual delete+insert for each upload runs as a single plpgsql
-- function call (`supabase.rpc(...)`) — a Postgres function body runs as
-- one implicit transaction, so any failure partway through (e.g. one bad
-- row) rolls back everything in that call automatically, and a file is
-- never partially committed.
--
-- Every delete below is `where id is not null` (never a bare `delete from
-- ...;`) — this project's Postgres rejects an unqualified DELETE even from
-- inside a plpgsql function body (confirmed live: "DELETE requires a WHERE
-- clause", error 21000), the same reason amazonReportUpload.ts's
-- truncateAndInsert and productMarketingUpload.ts's truncateAndInsert
-- already use `.delete().not("id", "is", null)` instead of a bare delete.
-- never partially committed.

create or replace function public.replace_barm_fba_daily_sales(rows jsonb)
returns void
language plpgsql
as $$
begin
  delete from public.barm_fba_daily_sales where id is not null;
  insert into public.barm_fba_daily_sales
    (purchase_date, fulfillment_channel, product_name, sku, quantity, ship_state)
  select
    (r->>'purchase_date')::date,
    r->>'fulfillment_channel',
    r->>'product_name',
    r->>'sku',
    (r->>'quantity')::integer,
    r->>'ship_state'
  from jsonb_array_elements(rows) as r;
end;
$$;

create or replace function public.replace_barm_fba_stock_snapshot(rows jsonb)
returns void
language plpgsql
as $$
begin
  delete from public.barm_fba_stock_snapshot where id is not null;
  insert into public.barm_fba_stock_snapshot
    (report_date, fnsku, fulfillment_center, asin, msku, disposition, ending_warehouse_balance)
  select
    (r->>'report_date')::date,
    r->>'fnsku',
    r->>'fulfillment_center',
    r->>'asin',
    r->>'msku',
    r->>'disposition',
